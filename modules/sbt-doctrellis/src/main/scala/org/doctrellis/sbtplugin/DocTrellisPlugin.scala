package org.doctrellis.sbtplugin

import cats.effect.IO as CatsIO
import cats.effect.unsafe.implicits.global
import laika.api.Transformer
import laika.format.{HTML, Markdown}
import laika.helium.Helium
import laika.io.syntax.*
import mdoc.MdocPlugin
import mdoc.MdocPlugin.autoImport.*
import sbt.*
import sbt.Keys.*

import java.io.IOException
import java.net.{BindException, InetSocketAddress}
import java.nio.file.Path
import java.util.concurrent.atomic.{AtomicBoolean, AtomicReference}
import java.util.concurrent.{CountDownLatch, Executors, TimeUnit}
import scala.util.control.NonFatal

object DocTrellisPlugin extends AutoPlugin:

  private val processMdoc = taskKey[Unit](
    "Process DocTrellis Markdown with the mdoc programmatic API",
  )
  private val renderSite = taskKey[Unit](
    "Render the processed DocTrellis Markdown with Laika",
  )

  object autoImport:
    val doctrellisSourceDirectory =
      settingKey[File]("Markdown source directory processed by mdoc")
    val doctrellisMdocDirectory =
      settingKey[File]("Directory containing Markdown generated by mdoc")
    val doctrellisOutputDirectory =
      settingKey[File]("Directory containing the generated HTML site")
    val doctrellisHost =
      settingKey[String]("Host interface for the local preview server")
    val doctrellisPort =
      settingKey[Int]("TCP port for the local preview server")
    val doctrellisBuild = taskKey[Unit](
      "Run mdoc, then render the result to HTML with Laika and Helium",
    )
    val doctrellisPreview =
      taskKey[Unit]("Build the documentation and serve it until interrupted")

  import autoImport.*

  override def requires: Plugins      = plugins.JvmPlugin && MdocPlugin
  override def trigger: PluginTrigger = noTrigger

  override lazy val projectSettings: Seq[Def.Setting[?]] = Seq(
    doctrellisSourceDirectory := baseDirectory.value / "docs",
    doctrellisMdocDirectory := baseDirectory.value / "target" / "doctrellis" / "mdoc",
    doctrellisOutputDirectory := baseDirectory.value / "target" / "doctrellis" / "site",
    doctrellisHost := "127.0.0.1",
    doctrellisPort := 4242,
    mdocIn         := doctrellisSourceDirectory.value,
    mdocOut        := doctrellisMdocDirectory.value,
    processMdoc    := Def.uncached {
      val source        = doctrellisSourceDirectory.value
      val mdocDirectory = doctrellisMdocDirectory.value
      val log           = streams.value.log
      sbt.IO.delete(mdocDirectory)
      sbt.IO.createDirectory(mdocDirectory)
      log.info(s"DocTrellis: running mdoc from ${source.getAbsolutePath}")
      val converter = fileConverter.value
      val classpath = (Compile / fullClasspath).value.map(entry =>
        converter.toPath(entry.data),
      )
      MdocProcessor.process(
        source.toPath,
        mdocDirectory.toPath,
        baseDirectory.value.toPath,
        classpath,
        (Compile / scalacOptions).value,
        mdocExtraArguments.value,
        mdocVariables.value,
        log.info,
        log.warn,
      )
    },
    renderSite := Def.uncached {
      val mdocDirectory = doctrellisMdocDirectory.value
      val output        = doctrellisOutputDirectory.value
      val log           = streams.value.log

      sbt.IO.delete(output)
      sbt.IO.createDirectory(output)
      log.info(
        s"DocTrellis: rendering HTML with Laika and the Helium theme into ${output.getAbsolutePath}",
      )
      val rendered = try
        Transformer
          .from(Markdown)
          .to(HTML)
          .using(Markdown.GitHubFlavor, GfmTaskLists)
          .parallel[CatsIO]
          .withTheme(
            Helium.defaults.site.inlineCSS(GfmTaskLists.themeCSS).build,
          )
          .build
          .use(
            _.fromDirectory(mdocDirectory.getAbsolutePath)
              .toDirectory(output.getAbsolutePath)
              .transform,
          )
          .unsafeRunSync()
      catch
        case NonFatal(error) =>
          sys.error(s"DocTrellis Laika rendering failed: ${error.getMessage}")

      log.info(
        s"DocTrellis: Laika rendered ${rendered.allDocuments.map(_.path).mkString(", ")}",
      )

      val index = output / "index.html"
      if !index.isFile then
        sys.error(
          s"DocTrellis did not generate an index page at ${index.getAbsolutePath}",
        )
      log.success(s"DocTrellis site generated at ${output.getAbsolutePath}")
      ()
    },
    doctrellisBuild := Def.uncached {
      Def
        .sequential(
          processMdoc,
          renderSite,
        )
        .value
    },
    doctrellisPreview := Def.uncached {
      doctrellisBuild.value
      val site      = doctrellisOutputDirectory.value
      val workspace = baseDirectory.value
      val host      = doctrellisHost.value
      val port      = doctrellisPort.value
      val log       = streams.value.log

      try PreviewServer.serve(site.toPath, workspace.toPath, host, port, log)
      catch
        case error: BindException =>
          sys.error(
            s"DocTrellis preview could not bind to $host:$port; the port may already be in use: ${error.getMessage}",
          )
        case error: IOException =>
          sys.error(
            s"DocTrellis preview server failed at http://$host:$port: ${error.getMessage}",
          )
    },
  )

private[sbtplugin] object PreviewServer:
  def serve(
      root: Path,
      workspace: Path,
      host: String,
      port: Int,
      log: Logger,
  ): Unit =
    val controlConfig = PreviewControlConfig.fromEnvironment(workspace, sys.env)
    PreviewHost.requireCompatible(host, controlConfig.nonEmpty)
    val binding = PreviewHttpBinding.start(root, host, port)
    val stopped = CountDownLatch(1)

    val shutdown = PreviewServerShutdown(
      stopServer = () => binding.stopServer(),
      stopExecutor = () => binding.stopExecutor(),
      signalStopped = () => stopped.countDown(),
    )

    val control = AtomicReference[PreviewControlServer]()

    val shutdownHook = Thread(
      () =>
        var failure = Option.empty[Throwable]

        def attempt(action: => Unit): Unit =
          try action
          catch
            case NonFatal(error) =>
              failure match
                case None           => failure = Some(error)
                case Some(existing) => existing.addSuppressed(error)

        attempt(shutdown.stop())
        attempt(Option(control.get()).foreach(_.close()))
        failure.foreach(throw _)
      ,
      "doctrellis-preview-shutdown",
    )

    java.lang.Runtime.getRuntime.addShutdownHook(shutdownHook)
    var primaryFailure = Option.empty[Throwable]
    try
      controlConfig
        .map(config =>
          PreviewControlServer.open(
            config = config,
            readyUrl = binding.url,
            onStop = () => shutdown.stop(),
            log = log,
          ),
        )
        .foreach(control.set)
      log.success(s"DocTrellis preview ready at ${binding.url}")
      log.info("Press Ctrl+C to stop the preview server.")
      stopped.await()
    catch
      case _: InterruptedException => Thread.currentThread().interrupt()
      case error: Throwable        =>
        primaryFailure = Some(error)
        throw error
    finally
      try
        var restoreInterrupt               = Thread.interrupted()
        var cleanupFailure                 = Option.empty[Throwable]
        def cleanup(action: => Unit): Unit =
          try action
          catch
            case _: InterruptedException => restoreInterrupt = true
            case NonFatal(error)         =>
              cleanupFailure match
                case None           => cleanupFailure = Some(error)
                case Some(existing) => existing.addSuppressed(error)

        val currentControl = Option(control.get())
        cleanup(
          currentControl.foreach(
            _.awaitStopAcknowledgedIfRequested(1L, TimeUnit.SECONDS),
          ),
        )
        cleanup(currentControl.foreach(_.close()))
        cleanup(shutdown.stop())
        if restoreInterrupt then Thread.currentThread().interrupt()
        cleanupFailure.foreach: error =>
          primaryFailure match
            case Some(primary) => primary.addSuppressed(error)
            case None          => throw error
      finally
        try java.lang.Runtime.getRuntime.removeShutdownHook(shutdownHook)
        catch case _: IllegalStateException => ()

private[sbtplugin] object PreviewHost:
  def requireCompatible(host: String, controlEnabled: Boolean): Unit =
    if controlEnabled && host != "127.0.0.1" then
      throw IllegalArgumentException(
        "DocTrellis IPC preview requires doctrellisHost := \"127.0.0.1\".",
      )

private[sbtplugin] final class PreviewHttpBinding private (
    val url: String,
    val port: Int,
    server: com.sun.net.httpserver.HttpServer,
    executor: java.util.concurrent.ExecutorService,
):
  def stopServer(): Unit = server.stop(0)

  def stopExecutor(): Unit = executor.shutdownNow()

private[sbtplugin] object PreviewHttpBinding:
  def start(root: Path, host: String, port: Int): PreviewHttpBinding =
    val executor = Executors.newCachedThreadPool()
    var server   = Option.empty[com.sun.net.httpserver.HttpServer]
    try
      val created = com.sun.net.httpserver.HttpServer.create(
        InetSocketAddress(host, port),
        0,
      )
      server = Some(created)
      created.createContext("/", StaticSiteHandler(root))
      created.setExecutor(executor)
      created.start()
      val actualPort = created.getAddress.getPort
      new PreviewHttpBinding(
        url = s"http://$host:$actualPort",
        port = actualPort,
        server = created,
        executor = executor,
      )
    catch
      case NonFatal(error) =>
        try server.foreach(_.stop(0))
        catch case NonFatal(cleanupError) => error.addSuppressed(cleanupError)
        try executor.shutdownNow()
        catch case NonFatal(cleanupError) => error.addSuppressed(cleanupError)
        throw error

private[sbtplugin] final class PreviewServerShutdown(
    stopServer: () => Unit,
    stopExecutor: () => Unit,
    signalStopped: () => Unit,
):
  private val stopped = AtomicBoolean(false)

  def stop(): Unit =
    if stopped.compareAndSet(false, true) then
      var failure = Option.empty[Throwable]

      def attempt(action: () => Unit): Unit =
        try action()
        catch
          case NonFatal(error) =>
            failure match
              case None           => failure = Some(error)
              case Some(existing) => existing.addSuppressed(error)

      attempt(stopServer)
      attempt(stopExecutor)
      attempt(signalStopped)
      failure.foreach(throw _)
