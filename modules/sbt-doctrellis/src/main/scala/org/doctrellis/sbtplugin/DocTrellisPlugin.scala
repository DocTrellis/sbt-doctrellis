package org.doctrellis.sbtplugin

import cats.effect.IO as CatsIO
import cats.effect.unsafe.implicits.global
import laika.api.Transformer
import laika.format.{HTML, Markdown}
import laika.helium.Helium
import laika.io.syntax.*
import mdoc.MdocPlugin
import mdoc.MdocPlugin.autoImport.*
import sbt.*
import sbt.Keys.*

import java.io.IOException
import java.net.{BindException, InetSocketAddress}
import java.nio.file.Path
import java.util.concurrent.{CountDownLatch, Executors}
import scala.util.control.NonFatal

object DocTrellisPlugin extends AutoPlugin:

  private val processMdoc = taskKey[Unit](
    "Process DocTrellis Markdown with the mdoc programmatic API",
  )
  private val renderSite = taskKey[Unit](
    "Render the processed DocTrellis Markdown with Laika",
  )

  object autoImport:
    val doctrellisSourceDirectory =
      settingKey[File]("Markdown source directory processed by mdoc")
    val doctrellisMdocDirectory =
      settingKey[File]("Directory containing Markdown generated by mdoc")
    val doctrellisOutputDirectory =
      settingKey[File]("Directory containing the generated HTML site")
    val doctrellisHost =
      settingKey[String]("Host interface for the local preview server")
    val doctrellisPort =
      settingKey[Int]("TCP port for the local preview server")
    val doctrellisBuild = taskKey[Unit](
      "Run mdoc, then render the result to HTML with Laika and Helium",
    )
    val doctrellisPreview =
      taskKey[Unit]("Build the documentation and serve it until interrupted")

  import autoImport.*

  override def requires: Plugins      = plugins.JvmPlugin && MdocPlugin
  override def trigger: PluginTrigger = noTrigger

  override lazy val projectSettings: Seq[Def.Setting[?]] = Seq(
    doctrellisSourceDirectory := baseDirectory.value / "docs",
    doctrellisMdocDirectory := baseDirectory.value / "target" / "doctrellis" / "mdoc",
    doctrellisOutputDirectory := baseDirectory.value / "target" / "doctrellis" / "site",
    doctrellisHost := "127.0.0.1",
    doctrellisPort := 4242,
    mdocIn         := doctrellisSourceDirectory.value,
    mdocOut        := doctrellisMdocDirectory.value,
    processMdoc    := Def.uncached {
      val source        = doctrellisSourceDirectory.value
      val mdocDirectory = doctrellisMdocDirectory.value
      val log           = streams.value.log
      sbt.IO.delete(mdocDirectory)
      sbt.IO.createDirectory(mdocDirectory)
      log.info(s"DocTrellis: running mdoc from ${source.getAbsolutePath}")
      val converter = fileConverter.value
      val classpath = (Compile / fullClasspath).value.map(entry =>
        converter.toPath(entry.data),
      )
      MdocProcessor.process(
        source.toPath,
        mdocDirectory.toPath,
        baseDirectory.value.toPath,
        classpath,
        (Compile / scalacOptions).value,
        mdocExtraArguments.value,
        mdocVariables.value,
        log.info,
        log.warn,
      )
    },
    renderSite := Def.uncached {
      val mdocDirectory = doctrellisMdocDirectory.value
      val output        = doctrellisOutputDirectory.value
      val log           = streams.value.log

      sbt.IO.delete(output)
      sbt.IO.createDirectory(output)
      log.info(
        s"DocTrellis: rendering HTML with Laika and the Helium theme into ${output.getAbsolutePath}",
      )
      val rendered = try
        Transformer
          .from(Markdown)
          .to(HTML)
          .using(Markdown.GitHubFlavor)
          .parallel[CatsIO]
          .withTheme(Helium.defaults.build)
          .build
          .use(
            _.fromDirectory(mdocDirectory.getAbsolutePath)
              .toDirectory(output.getAbsolutePath)
              .transform,
          )
          .unsafeRunSync()
      catch
        case NonFatal(error) =>
          sys.error(s"DocTrellis Laika rendering failed: ${error.getMessage}")

      log.info(
        s"DocTrellis: Laika rendered ${rendered.allDocuments.map(_.path).mkString(", ")}",
      )

      val index = output / "index.html"
      if !index.isFile then
        sys.error(
          s"DocTrellis did not generate an index page at ${index.getAbsolutePath}",
        )
      log.success(s"DocTrellis site generated at ${output.getAbsolutePath}")
      ()
    },
    doctrellisBuild := Def.uncached {
      Def
        .sequential(
          processMdoc,
          renderSite,
        )
        .value
    },
    doctrellisPreview := Def.uncached {
      doctrellisBuild.value
      val site = doctrellisOutputDirectory.value
      val host = doctrellisHost.value
      val port = doctrellisPort.value
      val log  = streams.value.log

      try PreviewServer.serve(site.toPath, host, port, log)
      catch
        case error: BindException =>
          sys.error(
            s"DocTrellis preview could not bind to $host:$port; the port may already be in use: ${error.getMessage}",
          )
        case error: IOException =>
          sys.error(
            s"DocTrellis preview server failed at http://$host:$port: ${error.getMessage}",
          )
    },
  )

private[sbtplugin] object PreviewServer:
  def serve(root: Path, host: String, port: Int, log: Logger): Unit =
    val executor = Executors.newCachedThreadPool()
    val stopped  = CountDownLatch(1)
    val server   =
      com.sun.net.httpserver.HttpServer.create(InetSocketAddress(host, port), 0)
    server.createContext("/", StaticSiteHandler(root))
    server.setExecutor(executor)

    val shutdownHook = Thread(
      () =>
        server.stop(0)
        executor.shutdownNow()
        stopped.countDown()
      ,
      "doctrellis-preview-shutdown",
    )

    java.lang.Runtime.getRuntime.addShutdownHook(shutdownHook)
    try
      server.start()
      log.success(s"DocTrellis preview ready at http://$host:$port")
      log.info("Press Ctrl+C to stop the preview server.")
      stopped.await()
    catch case _: InterruptedException => Thread.currentThread().interrupt()
    finally
      server.stop(0)
      executor.shutdownNow()
      stopped.countDown()
      try java.lang.Runtime.getRuntime.removeShutdownHook(shutdownHook)
      catch case _: IllegalStateException => ()
